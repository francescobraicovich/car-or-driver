// DOM helpers: escaping.
// Pure numeric helpers (clamp, pct, last, csv) live in packages/core.
export function esc(s) {
  return String(s ?? '').replace(
    /[&<>"']/g,
    (c) =>
      ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#39;',
      })[c],
  );
}
