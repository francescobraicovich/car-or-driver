// Writes site/js/metrics-snapshot.js: the few figures the methodology page quotes from the metric suite, copied from the files that
// research/eval/regenerate.sh produces, so the page cannot drift from them.
//   node tools/make-metrics-snapshot.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const read = async (p) => JSON.parse(await readFile(`${ROOT}${p}`, 'utf8'));
const suite = await read('research/eval/suite.json');
const heads = await read('research/eval/heads-metrics.json');
const sim = await read('research/eval/simulation-optimum.json');
const need = (v, what) => {
  if (!Number.isFinite(v)) throw Error(`metrics snapshot: ${what} is missing or not a number`);
  return v;
};
const f = (v, d, what) => need(v, what).toFixed(d);
const b = suite.base;
const n = suite.final;
const out = {
  'm.slope.base': f(b['M.slope.movers.sel'], 2, 'M.slope.movers.sel'),
  'm.moves': String(need(n['M.moves.sel'], 'M.moves.sel')),
  'm.ratio.base': f(b['M.slope.ratio.sel'], 2, 'M.slope.ratio.sel'),
  'm.ratio.now': f(n['M.slope.ratio.sel'], 2, 'M.slope.ratio.sel'),
  'm.port.base': f(b['M.resid.weight.ratio.sel'], 2, 'M.resid.weight.ratio.sel'),
  'm.port.now': f(n['M.resid.weight.ratio.sel'], 2, 'M.resid.weight.ratio.sel'),
  'm.d2.base': f(b['T.D2'], 2, 'T.D2'),
  'm.d2.now': f(n['T.D2'], 2, 'T.D2'),
};
for (const w of ['w2', 'w3']) {
  out[`m.loss.base.${w}`] = f(b[`P.all.${w}`], 4, `P.all.${w}`);
  out[`m.loss.now.${w}`] = f(n[`P.all.${w}`], 4, `P.all.${w}`);
}
for (const [tag, win] of [
  ['a', '2002-11'],
  ['b', '2012-15'],
])
  for (const k of [5, 10]) {
    out[`m.tm.base.${tag}${k}`] = f(b[`S.tm.${win}.k${k}`], 3, `S.tm.${win}.k${k}`);
    out[`m.tm.now.${tag}${k}`] = f(n[`S.tm.${win}.k${k}`], 3, `S.tm.${win}.k${k}`);
    out[`m.stay.${tag}${k}`] = f(n[`S.stayLoss.${win}.k${k}`], 3, `S.stayLoss.${win}.k${k}`);
  }
for (const [k, v] of Object.entries({
  'm.heads.base': heads.loss2008.base,
  'm.heads.thu': heads.loss2008.thu,
  'm.heads.raceDay': heads.loss2008.raceDay,
}))
  out[k] = f(v, 4, k);
out['m.heads.calBase'] = f(heads.slope.base, 2, 'heads.slope.base');
out['m.heads.calThu'] = f(heads.slope.thu, 2, 'heads.slope.thu');
out['m.heads.ratioBase'] = f(heads.moverRatio.base, 2, 'heads.moverRatio.base');
out['m.heads.ratioThu'] = f(heads.moverRatio.thu, 2, 'heads.moverRatio.thu');
out['m.sim.drv.base'] = f(sim.default.rmseDriver.base, 1, 'sim rmse driver base');
out['m.sim.drv.now'] = f(sim.default.rmseDriver.now, 1, 'sim rmse driver now');

const body = Object.entries(out)
  .map(([k, v]) => `  '${k}': '${v}',`)
  .join('\n');
const text = `// GENERATED by tools/make-metrics-snapshot.mjs from research/eval/{suite,heads-metrics,simulation-optimum}.json: do not edit by hand.\n// Figures quoted by the methodology page (site/js/methodology-content.js); the sources are listed in docs/metrics.md.\nexport const METRICS = {\n${body}\n};\n`;
await writeFile(`${ROOT}site/js/metrics-snapshot.js`, text);
console.log(`wrote site/js/metrics-snapshot.js (${Object.keys(out).length} figures)`);
