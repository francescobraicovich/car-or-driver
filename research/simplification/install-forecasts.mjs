// Install accepted chronological linear heads and their independent Python fixtures.
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { referenceHeads, REFERENCE_COMMIT } from './reference-heads.mjs';

const report = JSON.parse(await readFile('research/simplification/selected-forecast-report.json', 'utf8'));
if (!report.acceptedPointGuards) throw Error('Forecast acceptance report is missing or failed');
if (report.referenceCommit !== REFERENCE_COMMIT) throw Error('Forecast report uses a different reference');
const heads = JSON.parse(await readFile('tmp/simplification/selected-forecast-heads.json', 'utf8'));
const reference = await referenceHeads();
const referenceYears = Object.keys(reference).map(Number).sort((a, b) => b - a);
for (const [year, bundle] of Object.entries(heads)) {
  // The six-coefficient grid-only head uses no form trackers; retain it.
  bundle.grid = reference[referenceYears.find((key) => key <= Number(year))].grid;
  for (const head of Object.values(bundle)) {
    if (head.family !== 'linear' || head.names.length !== head.coefficients.length || !head.coefficients.every(Number.isFinite))
      throw Error('Invalid linear forecast head');
  }
}
await writeFile('packages/core/src/state-space/forecast-heads.js',
  '// Generated by research/simplification/export-forecasts.py and install-forecasts.mjs.\n' +
  '// Ridge strengths use inner chronological validation; keys are the first forecast year.\n' +
  `export const STATE_SPACE_HEADS = ${JSON.stringify(heads)};\n`);
const fixtures = JSON.parse(await readFile('tmp/simplification/selected-inference-fixtures.json', 'utf8'));
const originalFixtures = JSON.parse(execFileSync('git', ['show', `${report.referenceCommit}:research/state-space/inference-fixtures.json`], { encoding: 'utf8' }));
fixtures.push(...originalFixtures.filter((fixture) => fixture.mode === 'grid'));
await writeFile('research/state-space/inference-fixtures.json', `${JSON.stringify(fixtures)}\n`);
console.log(`Installed ${Object.keys(heads).length} dated linear bundles and ${fixtures.length} cross-language fixtures`);
