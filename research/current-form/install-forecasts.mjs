// Install the explicitly retrospective, mover-priority component comparison.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { modelSourceHash } from '../../tools/model-source-hash.mjs';

const read = async (path) => JSON.parse(await readFile(path, 'utf8'));
const digest = async (path) => createHash('sha256').update(await readFile(path)).digest('hex');
const path = 'research/current-form/component-results.json';
const result = await read(path);
const selected = result.selected;
if (result.referenceSourceHash !== '7a44023e0b230847' || !result.postHoc || !result.originalPreGainFailed ||
    selected?.family !== 'continuous') throw Error('Expected the disclosed continuous-form follow-up');
for (const [source, hash] of Object.entries(result.sourceSha256)) {
  if (await digest(source) !== hash) throw Error(`Evaluated source changed: ${source}`);
}
const model = result.models[selected.mask];
if (!model?.followupEligible || !Object.values(model.followupChecks).every(Boolean) ||
    !(model.frozen.difference <= -0.010) ||
    model.ordinary.preCombined.candidate.loss > model.ordinary.preCombined.reference.loss ||
    result.frozenCoverage.moves !== 51 || result.frozenCoverage.cellsPerMove !== 4)
  throw Error('Selected form failed the disclosed mover-priority guards');
const heads = await read('tmp/current-form/selected-forecast-heads.json');
if (JSON.stringify(heads) !== JSON.stringify(selected.heads)) throw Error('Exported heads differ from the evaluated selection');
for (const year of [2008, 2012, 2016, 2021, 2026]) for (const mode of ['pre', 'post', 'qual', 'grid']) {
  const head = heads[year]?.[mode];
  if (head?.family !== 'linear' || head.names.length !== head.coefficients.length || !head.coefficients.every(Number.isFinite))
    throw Error(`Invalid head ${year}/${mode}`);
  head.formMethod = 'continuous';
}
const fixtures = await read('tmp/current-form/selected-inference-fixtures.json');
if (fixtures.length !== 480 || fixtures.some((fixture) => !Number.isFinite(fixture.expected))) throw Error('Invalid parity fixtures');
await writeFile('packages/core/src/state-space/forecast-heads.js',
  '// Generated by research/current-form/fit-components.py, export-fixtures.py and install-forecasts.mjs.\n' +
  '// Retrospective mover-priority selection; dated ridge heads use earlier seasons only.\n' +
  `export const STATE_SPACE_HEADS = ${JSON.stringify(heads)};\n`);
await writeFile('research/state-space/inference-fixtures.json', `${JSON.stringify(fixtures)}\n`);
const report = {
  referenceSourceHash: result.referenceSourceHash,
  candidate: `continuous-${selected.mask}`,
  protocol: result.protocol,
  resultsPath: path,
  resultsSha256: await digest(path),
  rowsSha256: result.rowsSha256,
  frozenSha256: result.frozenSha256,
  historicalEvidence: 'Retrospective; mover-priority selection was adopted after the initial overall-gain threshold failed.',
  originalGatePassed: false,
  postHoc: true,
  acceptedPointGuards: true,
  checks: model.followupChecks,
  modes: model.ordinary,
  folds: model.folds,
  frozenEvidenceMovers: model.frozen,
  frozenRatingPrimary: 0.6888431259752807,
  monitoring2026: selected.monitoring2026,
  publishedSourceHash: (await modelSourceHash()).sourceHash,
};
await writeFile('research/stable-ratings/selected-forecast-report.json', `${JSON.stringify(report, null, 2)}\n`);
console.log(`Installed ${report.candidate}; source ${report.publishedSourceHash}; original gate failure retained`);
