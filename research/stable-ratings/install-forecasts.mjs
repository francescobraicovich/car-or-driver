// Install only the accepted, provenance-checked chronological forecast export.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { modelSourceHash } from '../../tools/model-source-hash.mjs';

const reportPath = 'research/stable-ratings/selected-forecast-report.json';
const report = JSON.parse(await readFile(reportPath, 'utf8'));
if (!report.acceptedPointGuards || report.referenceSourceHash !== '928427f97ab9daf6' ||
  report.candidate !== 'neutral-temporal' || report.margins.pooled !== 0.003 || report.margins.fold !== 0.006)
  throw Error('Forecast report does not describe the selected model and protocol');
const fitText = await readFile('research/stable-ratings/forecast-results.json', 'utf8');
if (createHash('sha256').update(fitText).digest('hex') !== report.resultsSha256) throw Error('Forecast results changed after export');
const heads = JSON.parse(await readFile('tmp/stable-ratings/selected-forecast-heads.json', 'utf8'));
for (const year of [2008, 2012, 2016, 2021, 2026]) for (const mode of ['pre', 'post', 'qual', 'grid']) {
  const head = heads[year]?.[mode];
  if (head?.family !== 'linear' || head.names.length !== head.coefficients.length || !head.coefficients.every(Number.isFinite))
    throw Error(`Invalid forecast head ${year}/${mode}`);
}
const fixtures = JSON.parse(await readFile('tmp/stable-ratings/selected-inference-fixtures.json', 'utf8'));
if (fixtures.length !== 480 || fixtures.some((fixture) => !Number.isFinite(fixture.expected))) throw Error('Invalid inference fixtures');
await writeFile('packages/core/src/state-space/forecast-heads.js',
  '// Generated by research/stable-ratings/export-forecasts.py and install-forecasts.mjs.\n' +
  '// Ridge strengths use inner chronological validation; keys are the first forecast year.\n' +
  `export const STATE_SPACE_HEADS = ${JSON.stringify(heads)};\n`);
await writeFile('research/state-space/inference-fixtures.json', `${JSON.stringify(fixtures)}\n`);
report.publishedSourceHash = (await modelSourceHash()).sourceHash;
await writeFile(reportPath, `${JSON.stringify(report, null, 2)}\n`);
console.log(`Installed chronological linear heads and 480 parity fixtures (source ${report.publishedSourceHash})`);
